
CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL,
    due_date_time TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT chk_task_status
        CHECK (status IN (
            'PENDING',
            'IN_PROGRESS',
            'COMPLETED'
        ))
);
